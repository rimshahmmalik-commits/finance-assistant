def generate_invoice_pdf(
    invoice_number,
    client,
    amount,
    status,
    invoice_date,
    due_date
):
    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=50,
        leftMargin=50,
        topMargin=50,
        bottomMargin=50,
    )

    styles = getSampleStyleSheet()

    content = []

    content.append(
        Paragraph(
            "<b>FINANCE ASSISTANT</b>",
            styles["Title"]
        )
    )

    content.append(
        Paragraph(
            "Professional Invoice",
            styles["Heading2"]
        )
    )

    content.append(
        Spacer(1, 25)
    )

    invoice_details = [
        ["Invoice Number", invoice_number],
        ["Client", client],
        ["Invoice Date", invoice_date or "—"],
        ["Due Date", due_date or "—"],
        ["Status", status],
    ]

    details_table = Table(
        invoice_details,
        colWidths=[150, 300]
    )

    details_table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (0, -1),
                colors.HexColor("#F1F3F5")
            ),
            (
                "FONTNAME",
                (0, 0),
                (0, -1),
                "Helvetica-Bold"
            ),
            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.5,
                colors.grey
            ),
            (
                "PADDING",
                (0, 0),
                (-1, -1),
                10
            ),
        ])
    )

    content.append(details_table)

    content.append(
        Spacer(1, 30)
    )

    amount_table = Table(
        [
            ["Description", "Amount"],
            [
                "Invoice Amount",
                f"PKR {amount:,.2f}"
            ]
        ],
        colWidths=[300, 150]
    )

    amount_table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, 0),
                colors.HexColor("#212529")
            ),
            (
                "TEXTCOLOR",
                (0, 0),
                (-1, 0),
                colors.white
            ),
            (
                "FONTNAME",
                (0, 0),
                (-1, 0),
                "Helvetica-Bold"
            ),
            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.5,
                colors.grey
            ),
            (
                "ALIGN",
                (1, 0),
                (1, -1),
                "RIGHT"
            ),
            (
                "PADDING",
                (0, 0),
                (-1, -1),
                10
            ),
        ])
    )

    content.append(amount_table)

    content.append(
        Spacer(1, 35)
    )

    content.append(
        Paragraph(
            "Generated by Finance Assistant",
            styles["Normal"]
        )
    )

    document.build(content)

    buffer.seek(0)

    return buffer


