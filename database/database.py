def get_transaction_summary():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    COALESCE(
                        SUM(
                            CASE
                                WHEN LOWER(transaction_type) = 'income'
                                THEN amount
                                ELSE 0
                            END
                        ),
                        0
                    ) AS total_income,

                    COALESCE(
                        SUM(
                            CASE
                                WHEN LOWER(transaction_type) = 'expense'
                                THEN amount
                                ELSE 0
                            END
                        ),
                        0
                    ) AS total_expenses

                FROM transactions
                """
            )

            result = cursor.fetchone()

            total_income = float(result[0] or 0)
            total_expenses = float(result[1] or 0)

            return {
                "income": total_income,
                "expenses": total_expenses,
                "net": total_income - total_expenses
            }


