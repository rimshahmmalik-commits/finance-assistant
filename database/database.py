def get_invoice_management_data():
    """
    Fetch invoices and total payments in one database query.
    """

    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                SELECT
                    i.invoice_number,
                    i.client,
                    i.amount,
                    i.status,
                    i.invoice_date,
                    i.due_date,
                    COALESCE(SUM(p.amount_paid), 0) AS total_paid
                FROM invoices i
                LEFT JOIN payment_events p
                    ON p.invoice_number = i.invoice_number
                GROUP BY
                    i.id,
                    i.invoice_number,
                    i.client,
                    i.amount,
                    i.status,
                    i.invoice_date,
                    i.due_date
                ORDER BY i.id DESC
            """)

            return cursor.fetchall()


