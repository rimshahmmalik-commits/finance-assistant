def get_payment_summary(invoice_number):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    i.amount,
                    COALESCE(SUM(p.amount_paid), 0) AS total_paid,
                    COUNT(p.id) AS payment_count,
                    MAX(p.recorded_at) AS last_payment_at
                FROM invoices i
                LEFT JOIN payment_events p
                    ON p.invoice_number = i.invoice_number
                WHERE i.invoice_number = %s
                GROUP BY i.amount
                """,
                (invoice_number,)
            )

            row = cursor.fetchone()

            if not row:
                return None

            invoice_amount = float(row[0] or 0)
            total_paid = float(row[1] or 0)

            return {
                "invoice_amount": invoice_amount,
                "total_paid": total_paid,
                "remaining": max(
                    invoice_amount - total_paid,
                    0
                ),
                "payment_count": int(row[2] or 0),
                "last_payment_at": row[3],
                "is_paid": total_paid >= invoice_amount
            }


