def get_reminder_queue():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                SELECT
                    i.invoice_number,
                    i.client,
                    i.amount,
                    i.due_date,
                    i.status,
                    c.email,
                    COALESCE(SUM(p.amount_paid), 0) AS total_paid
                FROM invoices i
                LEFT JOIN clients c
                    ON i.client = c.company
                LEFT JOIN payment_events p
                    ON i.invoice_number = p.invoice_number
                GROUP BY
                    i.invoice_number,
                    i.client,
                    i.amount,
                    i.due_date,
                    i.status,
                    c.email
            """)

            rows = cursor.fetchall()

    from datetime import date, timedelta

    today = date.today()
    queue = []

    for row in rows:
        invoice_number = row[0]
        client = row[1]
        amount = float(row[2] or 0)
        due_date = row[3]
        status = row[4]
        email = row[5]
        total_paid = float(row[6] or 0)

        remaining = max(amount - total_paid, 0)

        # Nothing to chase if already fully paid
        if remaining <= 0:
            continue

        if not due_date:
            continue

        # PostgreSQL may already return a date object
        if isinstance(due_date, str):
            due_date = date.fromisoformat(due_date)

        if due_date < today:
            reminder_type = "Overdue"

        elif due_date == today:
            reminder_type = "Due Today"

        elif due_date <= today + timedelta(days=3):
            reminder_type = "Due Soon"

        else:
            continue

        queue.append({
            "invoice_number": invoice_number,
            "client": client,
            "email": email,
            "amount": amount,
            "remaining": remaining,
            "due_date": due_date.isoformat(),
            "status": status,
            "reminder_type": reminder_type,
        })

    return queue

