# --------------------------------------------------
# ENVIRONMENT / CONNECTION
# --------------------------------------------------

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError(
        "DATABASE_URL was not found. "
        "Make sure it exists in your .env file."
    )

POOL = ConnectionPool(
    conninfo=DATABASE_URL,
    min_size=1,
    max_size=5,
    timeout=30,
    kwargs={
        "autocommit": True
    },
    open=True
)


def get_connection():
    return POOL.connection()


