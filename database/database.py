def get_monthly_profit_and_loss(year, month):
    """
    Returns income, expenses and net profit/loss
    for a selected month.
    """

    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    COALESCE(
                        SUM(
                            CASE
                                WHEN LOWER(transaction_type) = 'income'
                                THEN amount
                                ELSE 0
                            END
                        ),
                        0
                    ) AS income,

                    COALESCE(
                        SUM(
                            CASE
                                WHEN LOWER(transaction_type) = 'expense'
                                THEN amount
                                ELSE 0
                            END
                        ),
                        0
                    ) AS expenses

                FROM transactions

                WHERE EXTRACT(YEAR FROM transaction_date) = %s
                AND EXTRACT(MONTH FROM transaction_date) = %s
                """,
                (
                    year,
                    month
                )
            )

            row = cursor.fetchone()

            income = float(row[0] or 0)
            expenses = float(row[1] or 0)

            return {
                "income": income,
                "expenses": expenses,
                "net_profit": income - expenses
            }


def get_monthly_expense_breakdown(year, month):
    """
    Expense totals grouped by category
    for a selected month.
    """

    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    category,
                    COALESCE(SUM(amount), 0) AS total

                FROM transactions

                WHERE LOWER(transaction_type) = 'expense'
                AND EXTRACT(YEAR FROM transaction_date) = %s
                AND EXTRACT(MONTH FROM transaction_date) = %s

                GROUP BY category
                ORDER BY total DESC
                """,
                (
                    year,
                    month
                )
            )

            rows = cursor.fetchall()

            return [
                {
                    "category": row[0] or "Uncategorized",
                    "amount": float(row[1] or 0)
                }
                for row in rows
            ]


def get_monthly_cash_flow():
    """
    Monthly income, expenses and net cash flow.
    """

    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    DATE_TRUNC(
                        'month',
                        transaction_date
                    ) AS month,

                    COALESCE(
                        SUM(
                            CASE
                                WHEN LOWER(transaction_type) = 'income'
                                THEN amount
                                ELSE 0
                            END
                        ),
                        0
                    ) AS income,

                    COALESCE(
                        SUM(
                            CASE
                                WHEN LOWER(transaction_type) = 'expense'
                                THEN amount
                                ELSE 0
                            END
                        ),
                        0
                    ) AS expenses

                FROM transactions

                GROUP BY DATE_TRUNC(
                    'month',
                    transaction_date
                )

                ORDER BY month ASC
                """
            )

            rows = cursor.fetchall()

            result = []

            for row in rows:
                income = float(row[1] or 0)
                expenses = float(row[2] or 0)

                result.append({
                    "month": row[0],
                    "income": income,
                    "expenses": expenses,
                    "net": income - expenses
                })

            return result


